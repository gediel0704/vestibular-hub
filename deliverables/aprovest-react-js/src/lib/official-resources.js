export function resourcesForExam(exam, kind = "Todos", search = "") {
  const query = search.toLocaleLowerCase("pt-BR").trim();
  return officialResources.filter((resource) => {
    const matchesExam = resource.exam === exam || resource.exam === "Todas";
    const matchesKind = kind === "Todos" || resource.kind === kind;
    const text = `${resource.title} ${resource.description} ${resource.publisher}`;
    return matchesExam && matchesKind && text.toLocaleLowerCase("pt-BR").includes(query);
  });
}